//! Internal telemetry event model.
//!
//! Every timestamp carries its clock domain. Durations are only computed between timestamps
//! of the same domain; [`Timestamp::since`] refuses mixed domains instead of guessing a
//! conversion.

use serde::{Deserialize, Serialize};

/// Clock domain of a timestamp.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Clock {
    /// `CLOCK_MONOTONIC` in nanoseconds (SurfaceFlinger, ftrace `mono`, uprobes via
    /// `bpf_ktime_get_ns`).
    Monotonic,
    /// `CLOCK_BOOTTIME` in nanoseconds (includes suspend).
    Boottime,
    /// Synthetic clock of a replayed or generated trace.
    Synthetic,
}

/// A point in time, in nanoseconds, in a known clock domain.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct Timestamp {
    pub clock: Clock,
    pub ns: u64,
}

impl Timestamp {
    pub const fn new(clock: Clock, ns: u64) -> Self {
        Self { clock, ns }
    }

    /// `self - earlier` in nanoseconds, or `None` if the clocks differ or time went backwards.
    pub fn since(self, earlier: Timestamp) -> Option<u64> {
        if self.clock != earlier.clock {
            return None;
        }
        self.ns.checked_sub(earlier.ns)
    }
}

/// Where a frame observation came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TelemetrySource {
    /// `dumpsys SurfaceFlinger --latency <layer>`: present/ready timestamps per buffer.
    SurfaceFlingerLatency,
    /// Replayed trace file.
    Replay,
    /// Generated by tests.
    Synthetic,
}

/// One frame as observed by a telemetry backend.
///
/// `present` is when the frame reached the display (or the best available proxy).
/// `ready` is when the producer's buffer became ready (GPU fence signalled), if known.
/// `desired_present` is when the producer asked for the frame to be presented, if known.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FrameEvent {
    pub source: TelemetrySource,
    pub present: Timestamp,
    pub ready: Option<Timestamp>,
    pub desired_present: Option<Timestamp>,
}

/// Measurement quality of a value shown to users or used by the controller.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Provenance {
    /// Read directly from a hardware or OS interface.
    Measured,
    /// Derived from measured values by a model (e.g. bottleneck class, CPCS weights).
    Estimated,
    /// Not available on this device or right now.
    Unavailable,
}

/// A value with its provenance, so diagnostics never present estimates as measurements.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct Observed<T> {
    pub value: Option<T>,
    pub provenance: Provenance,
}

impl<T> Observed<T> {
    pub fn measured(v: T) -> Self {
        Self {
            value: Some(v),
            provenance: Provenance::Measured,
        }
    }
    pub fn estimated(v: T) -> Self {
        Self {
            value: Some(v),
            provenance: Provenance::Estimated,
        }
    }
    pub fn unavailable() -> Self {
        Self {
            value: None,
            provenance: Provenance::Unavailable,
        }
    }
}

/// Per-sample hardware evidence the bottleneck classifier may use. Every field is optional
/// because availability differs per device.
#[derive(Debug, Clone, Copy, Default, PartialEq, Serialize, Deserialize)]
pub struct LoadEvidence {
    /// Highest single-thread CPU busy fraction (0..=1) of the foreground process over the
    /// last window, from `/proc/<pid>/task/*/stat`.
    pub max_thread_busy: Option<f64>,
    /// GPU busy fraction (0..=1) from a vendor interface (e.g. kgsl `gpu_busy_percentage`).
    pub gpu_busy: Option<f64>,
    /// True when a CPU policy's `scaling_max_freq` is below `cpuinfo_max_freq`, i.e. the
    /// maximum is being capped by thermal or power management.
    pub cpu_max_capped: Option<bool>,
}
